import { defineStore } from 'pinia'
import type { OwnerContext } from '../types'

/**
 * Navigator v2 editor-session locks (Phase 26.3, Part 13).
 *
 * A lock is a purely IN-EDITOR concept: it is NOT persisted, NOT a payload
 * field, and has NO effect on published/public output. It only marks a node so
 * the Navigator can guard structural edits (move/delete/drag) against accidental
 * changes — locked nodes stay fully selectable and inspectable.
 *
 * Locks are scoped per OWNER (`type:id`), so switching between the page and post
 * being edited never leaks one document's locks into another. Because ids are
 * regenerated by duplicate/paste and removed by delete, {@link prune} drops any
 * locked id no longer present after a tree refresh, so the set never accumulates
 * stale entries.
 */
function ownerKey(owner: OwnerContext | null): string {
  return owner ? `${owner.type}:${owner.id}` : '∅'
}

export const useNavigatorLocksStore = defineStore('pbNavigatorLocks', {
  state: () => ({
    /** owner key ("page:12") => locked component ids. */
    byOwner: {} as Record<string, string[]>,
  }),

  getters: {
    /** The locked-id set for an owner, ready to hand to `describeNode`. */
    lockedSet(state) {
      return (owner: OwnerContext | null): ReadonlySet<string> => new Set(state.byOwner[ownerKey(owner)] ?? [])
    },
  },

  actions: {
    isLocked(owner: OwnerContext | null, id: string): boolean {
      return (this.byOwner[ownerKey(owner)] ?? []).includes(id)
    },

    lock(owner: OwnerContext | null, id: string): void {
      const key = ownerKey(owner)
      const ids = this.byOwner[key] ?? []
      if (!ids.includes(id)) {
        this.byOwner[key] = [...ids, id]
      }
    },

    unlock(owner: OwnerContext | null, id: string): void {
      const key = ownerKey(owner)
      const ids = this.byOwner[key]
      if (ids) {
        this.byOwner[key] = ids.filter((existing) => existing !== id)
      }
    },

    toggle(owner: OwnerContext | null, id: string): void {
      this.isLocked(owner, id) ? this.unlock(owner, id) : this.lock(owner, id)
    },

    /** Drop any locked id that is no longer present in the live tree. */
    prune(owner: OwnerContext | null, validIds: Iterable<string>): void {
      const key = ownerKey(owner)
      const ids = this.byOwner[key]
      if (!ids || ids.length === 0) {
        return
      }
      const valid = validIds instanceof Set ? validIds : new Set(validIds)
      const kept = ids.filter((id) => valid.has(id))
      if (kept.length !== ids.length) {
        this.byOwner[key] = kept
      }
    },
  },
})
