const GENERIC = 'squares-2x2'

/** Normalize a definition icon value (e.g. "heroicon-o-photo") to a bare name. */
function normalize(icon: string | null | undefined): string | null {
  if (!icon) return null
  return icon.replace(/^heroicon-[a-z]+-/, '').trim() || null
}

/**
 * Resolve a component's icon to an SVG path `d` string.
 * @param icon the raw definition icon (may be a heroicon name)
 * @param category the component category, used as a fallback
 */
export function resolveIconPath(icon?: string | null, category?: string | null): string {
  const name = normalize(icon)
  if (name && PATHS[name]) return PATHS[name]
  if (category && CATEGORY_ICON[category] && PATHS[CATEGORY_ICON[category]]) {
    return PATHS[CATEGORY_ICON[category]]
  }
  return PATHS[GENERIC]
}

/**
 * A full inline `<svg>` string for the resolved icon — for contexts that render
 * via v-html (e.g. the drag ghost), so they never show a raw "heroicon-…" name.
 */
export function resolveIconSvg(icon?: string | null, category?: string | null): string {
  const d = resolveIconPath(icon, category)
  return (
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" width="18" height="18">' +
    '<path stroke-linecap="round" stroke-linejoin="round" d="' +
    d +
    '" /></svg>'
  )
}
