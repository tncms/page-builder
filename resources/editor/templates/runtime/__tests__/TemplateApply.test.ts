// Phase 26.17 — applyTemplate / applyTemplateById through the existing insert pipeline.

import { describe, it, expect, beforeEach, vi } from 'vitest'
import { setActivePinia, createPinia } from 'pinia'

import { applyTemplate, applyTemplateById } from '../applyTemplate'
import { TemplateRuntimeError } from '../TemplateRuntimeError'
import { localTemplateProvider } from '../../provider'
import { patternProvider } from '../../../patterns/provider'
import { patternLibraryRegistry, createPatternDefinition, type PatternTree } from '../../../patterns/library'
import { useEditorStore } from '../../../stores/editor'
import type { TemplateDefinition } from '../../contracts'
import type { SectionNode, LayoutPayload } from '../../../types'

function section(type = 'section'): SectionNode {
  return { type, data: { background: '#fff' }, blocks: [{ type: 'heading', data: {} }] }
}
function pageTree(): PatternTree {
  return createPatternDefinition({ name: 'x', sections: [section()] }).tree
}
function treeTemplate(): TemplateDefinition {
  return { id: 'tpl-tree', name: 'Landing', layout: { kind: 'tree', tree: pageTree() } }
}

// A faithful `insert-pattern` fake: assign server ids recursively, select the new root.
function seedEditor() {
  const editor = useEditorStore()
  editor.currentPayload = { schema: 'pagebuilder/01', sections: [] } as LayoutPayload
  let n = 0
  const rekey = (node: SectionNode): SectionNode => {
    const id = `srv-${(n += 1)}`
    const data = { ...node.data }
    if (Array.isArray(data.blocks)) data.blocks = (data.blocks as SectionNode[]).map(rekey)
    return { ...node, id, data, ...(node.blocks ? { blocks: node.blocks.map(rekey) } : {}) }
  }
  const runCommand = vi.fn(async (before: LayoutPayload, command: string, params: Record<string, unknown>) => {
    if (command !== 'insert-pattern') return { payload: before, selection: { selected: null } }
    const added = (params.sections as SectionNode[]).map(rekey)
    return { payload: { ...before, sections: [...before.sections, ...added] }, selection: { selected: added[0].id } }
  })
  ;(editor as unknown as { client: unknown }).client = { runCommand }
  return { editor, runCommand }
}

beforeEach(() => {
  setActivePinia(createPinia())
  patternLibraryRegistry.clear()
  localTemplateProvider.clear()
})

describe('applyTemplate — success', () => {
  it('applies a tree template via one insert-pattern command (one undo, selection follows)', async () => {
    const { editor, runCommand } = seedEditor()
    const result = await applyTemplate(treeTemplate(), editor)

    expect(result.ok).toBe(true)
    expect(runCommand).toHaveBeenCalledTimes(1)
    expect(runCommand.mock.calls[0][1]).toBe('insert-pattern')
    expect(editor.undoStack).toHaveLength(1) // one logical history entry
    expect(editor.currentPayload.sections).toHaveLength(1)
    expect(editor.selectedComponentId).toBe('srv-1') // server-selected root
    expect(result.selected).toBe('srv-1')
    expect(result.resolved.source).toBe('tree')

    // ids regenerated by the canonical server path (id-free client payload).
    const sent = runCommand.mock.calls[0][2].sections as SectionNode[]
    expect(sent[0].id).toBeUndefined()
  })

  it('applies a composed template (patterns merged, one command)', async () => {
    const { editor, runCommand } = seedEditor()
    const a = patternProvider.register(createPatternDefinition({ name: 'A', sections: [section('hero')] }))
    const b = patternProvider.register(createPatternDefinition({ name: 'B', sections: [section('cta')] }))
    const tpl: TemplateDefinition = { id: 'tpl-c', name: 'Composed', layout: { kind: 'patterns', patternIds: [a.id, b.id] } }

    const result = await applyTemplate(tpl, editor)
    expect(result.ok).toBe(true)
    expect(runCommand).toHaveBeenCalledTimes(1)
    expect(editor.currentPayload.sections.map((s) => s.type)).toEqual(['hero', 'cta']) // merged in order
    expect(editor.undoStack).toHaveLength(1)
  })
})

describe('applyTemplate — atomic failure', () => {
  it('a resolution failure creates no command, no undo entry, and no mutation', async () => {
    const { editor, runCommand } = seedEditor()
    const before = JSON.stringify(editor.currentPayload)
    const tpl: TemplateDefinition = { id: 'bad', name: 'Bad', layout: { kind: 'patterns', patternIds: ['missing'] } }

    await expect(applyTemplate(tpl, editor)).rejects.toBeInstanceOf(TemplateRuntimeError)
    expect(runCommand).not.toHaveBeenCalled()
    expect(editor.undoStack).toHaveLength(0)
    expect(JSON.stringify(editor.currentPayload)).toBe(before) // BuilderState untouched
  })
})

describe('applyTemplateById', () => {
  it('applies a registered template', async () => {
    const { editor, runCommand } = seedEditor()
    localTemplateProvider.register(treeTemplate())
    const result = await applyTemplateById('tpl-tree', editor)
    expect(result.ok).toBe(true)
    expect(runCommand).toHaveBeenCalledTimes(1)
  })

  it('throws template_not_found for an unknown id and runs no command', async () => {
    const { editor, runCommand } = seedEditor()
    await expect(applyTemplateById('nope', editor)).rejects.toMatchObject({ code: 'template_not_found' })
    expect(runCommand).not.toHaveBeenCalled()
  })
})

